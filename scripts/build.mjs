/**
 * Production build: bundle + minify + code-split the ES modules, minify CSS,
 * hash every output file, and point index.html at the hashed entry files.
 * The complete output list is written into sw.js so the service worker can
 * precache every chunk (including lazily imported ones) for true offline use.
 * Source files stay in the repo so the app remains editable without a build.
 *
 * Run: npm run build
 */
import fs from 'node:fs';
import path from 'node:path';
import { build } from 'esbuild';

const root = path.resolve(import.meta.dirname, '..');
const assetsDir = path.join(root, 'assets');
const indexPath = path.join(root, 'index.html');
const swPath = path.join(root, 'sw.js');

const BUILD_START = '/* BUILD:START';
const BUILD_END = '/* BUILD:END */';

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

async function main() {
  fs.mkdirSync(assetsDir, { recursive: true });
  // Remove every previously generated hashed file, including split chunks.
  for (const entry of fs.readdirSync(assetsDir)) {
    if (/^(?:app|styles|report-image|chunk|speech|canvas)[.-][A-Za-z0-9]{8,10}\.(?:js|css)$/.test(entry)) {
      fs.rmSync(path.join(assetsDir, entry));
    }
  }

  const result = await build({
    absWorkingDir: root,
    entryPoints: ['app.js', 'styles.css'],
    bundle: true,
    format: 'esm',
    target: ['es2020'],
    minify: true,
    legalComments: 'none',
    splitting: true,
    outdir: assetsDir,
    entryNames: '[name].[hash]',
    chunkNames: '[name]-[hash]',
    write: false,
    metafile: true
  });

  const emitted = [];
  let jsName = '';
  let cssName = '';
  for (const file of result.outputFiles) {
    const name = path.basename(file.path);
    fs.writeFileSync(path.join(assetsDir, name), file.contents);
    emitted.push(`./assets/${name}`);
    if (/^app\./.test(name)) jsName = name;
    if (/^styles\./.test(name)) cssName = name;
  }
  if (!jsName || !cssName) throw new Error('Build did not emit both JS and CSS entries.');

  let html = fs.readFileSync(indexPath, 'utf8');
  html = html.replace(
    /<link rel="stylesheet" href="\.\/(?:styles\.css[^"]*|assets\/styles\.[^"]+)">/,
    `<link rel="stylesheet" href="./assets/${cssName}">`
  );
  html = html.replace(
    /<script type="module" src="\.\/(?:app\.js[^"]*|assets\/app\.[^"]+)"><\/script>/,
    `<script type="module" src="./assets/${jsName}"></script>`
  );
  fs.writeFileSync(indexPath, html);

  // Keep the SW precache list in sync with every emitted file, including the
  // lazily imported chunks, so offline works on the very first visit.
  const block = `${BUILD_START} — generated by scripts/build.mjs; do not edit by hand. */\nconst BUILD_ASSETS = ${JSON.stringify(emitted, null, 2)};\n${BUILD_END}`;
  const marker = new RegExp(`${escapeRegExp(BUILD_START)}[\\s\\S]*?${escapeRegExp(BUILD_END)}`);
  let sw = fs.readFileSync(swPath, 'utf8');
  if (!marker.test(sw)) throw new Error('sw.js is missing the BUILD:START/BUILD:END markers.');
  sw = sw.replace(marker, block);
  fs.writeFileSync(swPath, sw);

  const kb = (bytes) => `${(bytes / 1024).toFixed(1)} kB`;
  for (const file of result.outputFiles) {
    console.log(`built assets/${path.basename(file.path)} (${kb(file.contents.length)})`);
  }
  console.log('updated index.html and sw.js precache list');
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
